ALTER TABLE audit ENABLE ROW LEVEL SECURITY;
ALTER TABLE cooldown ENABLE ROW LEVEL SECURITY;
ALTER TABLE updates ENABLE ROW LEVEL SECURITY;
ALTER TABLE work_lock ENABLE ROW LEVEL SECURITY;
