CREATE SCHEMA IF NOT EXISTS vpn_bot;
SET search_path TO vpn_bot;

CREATE TABLE IF NOT EXISTS work_lock (
    id BIGINT PRIMARY KEY CHECK(id=1), owner TEXT NOT NULL, expires_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS chats (
    user_id BIGINT PRIMARY KEY, chat_id BIGINT NOT NULL,
    reachable BIGINT NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS actions (
    token TEXT PRIMARY KEY, actor BIGINT NOT NULL, kind TEXT NOT NULL,
    payload TEXT NOT NULL, expires DOUBLE PRECISION NOT NULL, consumed BIGINT DEFAULT 0
);
CREATE TABLE IF NOT EXISTS jobs (
    id BIGSERIAL PRIMARY KEY, actor BIGINT NOT NULL, body TEXT NOT NULL,
    created DOUBLE PRECISION NOT NULL, finished BIGINT DEFAULT 0, reported BIGINT DEFAULT 0
);
CREATE TABLE IF NOT EXISTS deliveries (
    job_id BIGINT NOT NULL REFERENCES jobs(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL, state TEXT NOT NULL DEFAULT 'pending',
    ready_at DOUBLE PRECISION NOT NULL DEFAULT 0,
    PRIMARY KEY(job_id,user_id)
);
CREATE TABLE IF NOT EXISTS audit (
    id BIGSERIAL PRIMARY KEY, at DOUBLE PRECISION NOT NULL, actor BIGINT NOT NULL,
    operation TEXT NOT NULL, detail TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS cooldown (
    id BIGINT PRIMARY KEY CHECK(id=1), until_at DOUBLE PRECISION NOT NULL
);
CREATE TABLE IF NOT EXISTS updates (
    update_id BIGINT PRIMARY KEY, processed_at DOUBLE PRECISION NOT NULL
);
CREATE INDEX IF NOT EXISTS delivery_pending ON deliveries(state, ready_at);
ALTER TABLE chats ENABLE ROW LEVEL SECURITY;
